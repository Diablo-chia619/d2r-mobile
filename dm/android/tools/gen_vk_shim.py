#!/usr/bin/env python3
"""从 NDK 的 Vulkan 头文件生成 vk_shim.c：把引擎需要的每个 Vulkan 入口都定义成转发函数。

为什么需要它：D2R 的手机宿主是直接链接系统 libvulkan 的（547 处调用、117 个不同入口）。
要换成 Turnip，就必须让这些调用经过我们自己选定的驱动，而不是系统 loader。
做法不是改 547 处调用，而是在链接期把符号“抢”过来：本文件定义了全部入口，
转发到 vk_runtime.c 里解析出来的真实函数指针（系统驱动或 Turnip，由配置决定）。

符号清单来源（权威）：对编好的 libdm.so 跑
  llvm-nm -D --undefined-only libdm.so | grep '^vk'
引擎新增 Vulkan 调用时，重新跑一遍这条命令、把新名字加进 SYMBOLS，再重新生成本文件。

用法：python gen_vk_shim.py <输出路径>
"""
from pathlib import Path
import re, sys

NDK = Path(r"D:/toolchains/android-sdk/ndk/29.0.14206865")
HEADERS = [
    NDK / "toolchains/llvm/prebuilt/windows-x86_64/sysroot/usr/include/vulkan/vulkan_core.h",
    NDK / "toolchains/llvm/prebuilt/windows-x86_64/sysroot/usr/include/vulkan/vulkan_android.h",
]

# 引擎 libdm.so 里以未定义符号形式出现的 Vulkan 入口（117 个，2026-11-12 实测）
SYMBOLS = """
vkAcquireNextImageKHR vkAllocateCommandBuffers vkAllocateDescriptorSets vkAllocateMemory
vkBeginCommandBuffer vkBindBufferMemory vkBindImageMemory vkCmdBeginQuery vkCmdBeginRenderPass
vkCmdBindDescriptorSets vkCmdBindIndexBuffer vkCmdBindPipeline vkCmdBindVertexBuffers vkCmdBlitImage
vkCmdClearAttachments vkCmdClearColorImage vkCmdClearDepthStencilImage vkCmdCopyBuffer
vkCmdCopyBufferToImage vkCmdCopyImage vkCmdCopyImageToBuffer vkCmdCopyQueryPoolResults vkCmdDispatch
vkCmdDraw vkCmdDrawIndexed vkCmdEndQuery vkCmdEndRenderPass vkCmdFillBuffer vkCmdPipelineBarrier
vkCmdPushConstants vkCmdResetQueryPool vkCmdResolveImage vkCmdSetScissor vkCmdSetViewport
vkCmdWriteTimestamp vkCreateAndroidSurfaceKHR vkCreateBuffer vkCreateBufferView vkCreateCommandPool
vkCreateComputePipelines vkCreateDescriptorPool vkCreateDescriptorSetLayout vkCreateDescriptorUpdateTemplate
vkCreateDevice vkCreateFence vkCreateFramebuffer vkCreateGraphicsPipelines vkCreateImage vkCreateImageView
vkCreateInstance vkCreatePipelineCache vkCreatePipelineLayout vkCreateQueryPool vkCreateRenderPass
vkCreateSampler vkCreateSemaphore vkCreateShaderModule vkCreateSwapchainKHR vkDestroyBuffer
vkDestroyBufferView vkDestroyCommandPool vkDestroyDescriptorPool vkDestroyDescriptorSetLayout
vkDestroyDescriptorUpdateTemplate vkDestroyDevice vkDestroyFence vkDestroyFramebuffer vkDestroyImage
vkDestroyImageView vkDestroyInstance vkDestroyPipeline vkDestroyPipelineCache vkDestroyPipelineLayout
vkDestroyQueryPool vkDestroyRenderPass vkDestroySampler vkDestroySemaphore vkDestroyShaderModule
vkDestroySurfaceKHR vkDestroySwapchainKHR vkEndCommandBuffer vkEnumerateDeviceExtensionProperties
vkEnumeratePhysicalDevices vkFlushMappedMemoryRanges vkFreeMemory vkGetBufferMemoryRequirements
vkGetDeviceProcAddr vkGetDeviceQueue vkGetFenceStatus vkGetImageMemoryRequirements vkGetPhysicalDeviceFeatures
vkGetPhysicalDeviceFeatures2 vkGetPhysicalDeviceFormatProperties vkGetPhysicalDeviceFormatProperties2
vkGetPhysicalDeviceImageFormatProperties vkGetPhysicalDeviceMemoryProperties vkGetPhysicalDeviceProperties
vkGetPhysicalDeviceProperties2 vkGetPhysicalDeviceQueueFamilyProperties vkGetPhysicalDeviceSurfaceCapabilitiesKHR
vkGetPhysicalDeviceSurfaceFormatsKHR vkGetPhysicalDeviceSurfaceSupportKHR vkGetPipelineCacheData
vkGetQueryPoolResults vkGetSwapchainImagesKHR vkInvalidateMappedMemoryRanges vkMapMemory vkQueuePresentKHR
vkQueueSubmit vkQueueWaitIdle vkResetCommandBuffer vkResetCommandPool vkResetFences vkUnmapMemory
vkUpdateDescriptorSets vkUpdateDescriptorSetWithTemplate vkWaitForFences
""".split()

TYPEDEF = re.compile(r"typedef\s+(.+?)\s*\(VKAPI_PTR\s+\*PFN_(\w+)\)\((.*?)\);")


def collect():
    found = {}
    for h in HEADERS:
        text = h.read_text(encoding="utf-8", errors="replace")
        for m in TYPEDEF.finditer(text):
            ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
            found[name] = (ret, params)
    return found


def split_params(params):
    """按顶层逗号切参数，返回 [(类型+名字文本, 名字)]；无参数返回 []。"""
    if not params or params == "void":
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    named = []
    for p in out:
        m = re.search(r"([A-Za-z_]\w*)\s*(\[\s*\d*\s*\])?$", p)
        if not m:
            raise SystemExit("参数解析失败: " + p)
        named.append((p, m.group(1)))
    return named


def main():
    out_path = Path(sys.argv[1])
    sigs = collect()
    missing = [s for s in SYMBOLS if s not in sigs]
    if missing:
        raise SystemExit("头文件里找不到这些入口的 PFN 定义: " + ", ".join(missing))

    lines = [
        "// 由 dm/android/tools/gen_vk_shim.py 生成，不要手改。",
        "// Generated by dm/android/tools/gen_vk_shim.py -- do not edit by hand.",
        "//",
        "// 每个 Vulkan 入口都在这里定义成转发体：先取 vk_runtime 解析好的真实函数指针，再调用它。",
        "// 编译时加 -fvisibility=hidden，符号不外露，引擎内部的调用因此绑定到本文件而不是系统 loader。",
        "// Every Vulkan entry point is defined here as a forwarder to the pointer vk_runtime resolved.",
        "// Built with -fvisibility=hidden so these definitions stay internal to libdm.so.",
        '#include "vk_runtime.h"',
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
    ]
    # 指针全局 + 名字表
    for name in SYMBOLS:
        lines.append(f"PFN_{name} p_{name};")
    lines.append("")
    lines.append("const dm_vk_slot dm_vk_slots[] = {")
    for name in SYMBOLS:
        lines.append(f'    {{"{name}", (void **)&p_{name}}},')
    lines.append("};")
    lines.append("const unsigned dm_vk_slot_count = sizeof(dm_vk_slots) / sizeof(dm_vk_slots[0]);")
    lines.append("")
    special = {"vkCreateInstance", "vkCreateDevice", "vkGetInstanceProcAddr", "vkGetDeviceProcAddr"}
    for name in SYMBOLS:
        ret, params = sigs[name]
        named = split_params(params)
        plist = ", ".join(p for p, _ in named) if named else "void"
        args = ", ".join(n for _, n in named)
        lines.append(f"VKAPI_ATTR {ret} VKAPI_CALL {name}({plist}) {{")
        if name == "vkCreateInstance":
            lines.append("    return dm_vk_create_instance(pCreateInfo, pAllocator, pInstance);")
        elif name == "vkCreateDevice":
            lines.append("    return dm_vk_create_device(physicalDevice, pCreateInfo, pAllocator, pDevice);")
        elif name == "vkGetInstanceProcAddr":
            lines.append("    return dm_vk_gipa(instance, pName);")
        elif name == "vkGetDeviceProcAddr":
            lines.append("    return dm_vk_gdpa(device, pName);")
        elif ret == "void":
            lines.append(f'    dm_vk_call_void((void **)&p_{name}, "{name}");')
            if args:
                lines.append(f"    p_{name}({args});")
        else:
            lines.append(f'    dm_vk_require((void **)&p_{name}, "{name}");')
            lines.append(f"    return p_{name}({args});")
        lines.append("}")
        lines.append("")
    lines += ["#ifdef __cplusplus", "}", "#endif", ""]
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"✓ 生成 {out_path}：{len(SYMBOLS)} 个入口，{len(lines)} 行")
    del special


if __name__ == "__main__":
    main()
